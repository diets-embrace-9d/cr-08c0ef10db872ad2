// Hong Kong is diglossic: people SPEAK Cantonese but WRITE Standard Written
// Chinese, which follows Mandarin grammar and word choice. Newspapers, signs,
// menus, official notices, textbooks, and TV subtitles are nearly all written
// in 書面語 — yet when read aloud in Hong Kong, every character is given its
// CANTONESE pronunciation (是 is read si6, never shì). So a newsreader says
// "si6" for a character an ordinary person would say "hai6" for in speech.
//
